function packageJson(manager: ManagerChoice | undefined): string {
  const pick = (names: readonly (keyof typeof REACT_PINS)[]): Record<string, string> =>
    Object.fromEntries(names.map((name) => [name, REACT_PINS[name]]));
  const manifest: Record<string, unknown> = {
    name: 'new-project',
    private: true,
    type: 'module',
    // Only the versioned form: a corepack pnpm/yarn shim refuses a bare name.
    ...(manager?.version !== undefined ? { packageManager: `${manager.name}@${manager.version}` } : {}),
    scripts: { dev: 'vite' },
    dependencies: pick(['@tanstack/react-router', 'react', 'react-dom']),
    devDependencies: pick([
      '@tanstack/router-plugin',
      '@types/react',
      '@types/react-dom',
      '@vitejs/plugin-react',
      'typescript',
      'vite',
    ]),
  };
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

